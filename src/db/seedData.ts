const makeFormat = (
  matches: number,
  runs: number,
  highestScore: number,
  battingAverage: number,
  strikeRate: number,
  hundreds: number,
  fifties: number,
  wickets: number,
  bowlingEconomy: number,
  bestBowling: string
): FormatStats => ({
  matches,
  innings: Math.round(matches * 0.9),
  runs,
  highestScore,
  notOuts: Math.round(matches * 0.15),
  fifties,
  hundreds,
  strikeRate,
  battingAverage,
  fours: Math.round(runs / 7.5),
  sixes: Math.round(runs / 25),
  ducks: Math.max(1, Math.round(matches * 0.04)),
  wickets,
  bowlingOvers: Math.round(wickets * 5.2),
  runsConceded: Math.round(wickets * bowlingEconomy * 4),
  bowlingEconomy,
  bowlingAverage: wickets > 0 ? parseFloat(((wickets * bowlingEconomy * 4) / wickets).toFixed(2)) : 0,
  bowlingStrikeRate: wickets > 0 ? parseFloat(((wickets * 30) / wickets).toFixed(1)) : 0,
  bestBowling,
  fourWicketHauls: Math.round(wickets / 18),
  fiveWicketHauls: Math.round(wickets / 35),
  catches: Math.round(matches * 0.45),
  runOuts: Math.round(matches * 0.08),
  stumpings: 0,
});

