import type { Match, Team, Tournament, Player, FormatStats, PlayerRole, BattingStyle, BowlingStyle } from '../types/cricket';

function createPlayerObj(
  id: string,
  name: string,
  role: PlayerRole,
  battingStyle: BattingStyle,
  bowlingStyle?: BowlingStyle,
  matches = 0,
  innings = 0,
  runs = 0,
  highestScore = 0,
  notOuts = 0,
  fifties = 0,
  hundreds = 0,
  strikeRate = 0,
  battingAverage = 0,
  wickets = 0,
  bowlingEconomy = 0,
  bowlingAverage = 0,
  bestBowling = '0/0',
  catches = 0,
  runOuts = 0,
  stumpings = 0
): Player {
  const stats: FormatStats = {
    matches,
    innings,
    runs,
    highestScore,
    notOuts,
    fifties,
    hundreds,
    strikeRate,
    battingAverage,
    fours: Math.round(runs / 7),
    sixes: Math.round(runs / 24),
    ducks: Math.max(0, matches - innings),
    wickets,
    bowlingOvers: Math.round(wickets * 4),
    runsConceded: Math.round(wickets * 4 * (bowlingEconomy || 7.5)),
    bowlingEconomy,
    bowlingAverage,
    bowlingStrikeRate: wickets > 0 ? (wickets * 4 * 6) / wickets : 0,
    bestBowling,
    fourWicketHauls: Math.round(wickets / 20),
    fiveWicketHauls: Math.round(wickets / 40),
    catches,
    runOuts,
    stumpings,
  };

  return {
    id,
    fanClubId: `FC-${id.toUpperCase()}`,
    name,
    country: 'International',
    nationality: 'Global',
    role,
    battingStyle,
    bowlingStyle,
    teams: [],
    isVerified: true,
    isInternational: true,
    isDomestic: false,
    isLocalClub: false,
    dataProvenance: {
      source: 'system',
      importedAt: '2026-11-01T00:00:00Z',
    },
    overallStats: stats,
    statsByFormat: { t20i: stats },
    achievements: [],
    careerHistory: [],
    followerCount: 500,
    matches,
    innings,
    runs,
    highestScore,
    notOuts,
    fifties,
    hundreds,
    strikeRate,
    battingAverage,
    wickets,
    bowlingEconomy,
    bowlingAverage,
    bestBowling,
    catches,
    runOuts,
    stumpings,
  };
}

